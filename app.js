function runCommand() {
  const c = String(state.commandValue || '').trim().toLowerCase();
  if (!c) return;
  if (c === 'help') {
    state.commandOutput = [
      'devices',
      'install',
      'shell am start',
      'logcat',
      'reboot',
    ].join('\n');
    log('Help command shown.');
  } else if (c.includes('devices')) {
    state.commandOutput = state.installedApps.length
      ? `List of devices attached\nmobile-lab-001\tdevice\n${state.packageName}\t${state.deviceState}`
      : 'List of devices attached\nmobile-lab-001\tdevice';
    log('devices command handled.');
  } else if (c.includes('install')) {
    installPackage();
    return;
  } else if (c.includes('shell am start')) {
    runApp();
    return;
  } else if (c.includes('logcat')) {
    state.commandOutput = state.logs.slice(-10).map((entry) => `[${entry.time}] ${entry.text}`).join('\n');
    log('logcat captured.');
  } else if (c.includes('reboot')) {
    resetDevice();
    state.commandOutput = 'Rebooting virtual device...';
  } else {
    state.commandOutput = `Command accepted: ${state.commandValue}`;
    log(`Command handled: ${state.commandValue}`);
  }
  render();
}

