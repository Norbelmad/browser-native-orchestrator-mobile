function renderBuild() {
  const root = qs('content');
  root.innerHTML = document.getElementById('buildTemplate').innerHTML;

  qs('fileCount').textContent = String(state.files.length);
  qs('taskCount').textContent = String(state.tasks.length);
  qs('workerCount').textContent = String(state.workers.length);
  qs('selectedFileLabel').textContent = state.selectedFile;
  qs('statusLabel').textContent = `${state.buildStatus} • ${state.currentTask}`;
  qs('projectName').value = state.projectName;
  qs('goal').value = state.goal;
  qs('prompt').value = state.prompt;
  qs('editor').value = selectedFileContent() || sourceDraft || '';
  qs('taskInput').value = state.taskInput || '';
  qs('searchFiles').value = state.searchText || '';

  renderTaskList();
  renderFileList();
  renderLogs();

  qs('projectName').oninput = () => { state.projectName = qs('projectName').value; saveState(); };
  qs('goal').oninput = () => { state.goal = qs('goal').value; saveState(); };
  qs('prompt').oninput = () => { state.prompt = qs('prompt').value; saveState(); };
  qs('editor').oninput = () => {
    sourceDraft = qs('editor').value;
    updateSelectedFileFromEditor(sourceDraft);
    saveState();
  };
  qs('taskInput').oninput = () => { state.taskInput = qs('taskInput').value; saveState(); };
  qs('searchFiles').oninput = () => { state.searchText = qs('searchFiles').value; saveState(); renderBuild(); };
}

