function slugify(text) {
  return String(text)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    || 'browser-native-orchestrator';
}

function toUint8Array(value) {
  if (value instanceof Uint8Array) return value;
  if (typeof value === 'string') return new TextEncoder().encode(value);
  if (value instanceof ArrayBuffer) return new Uint8Array(value);
  throw new TypeError('Unsupported data type');
}

function makeCrc32Table() {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) {
      c = ((c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1)) >>> 0;
    }
    table[n] = c >>> 0;
  }
  return table;
}

const CRC32_TABLE = makeCrc32Table();

function crc32(data) {
  const bytes = toUint8Array(data);
  let c = 0xFFFFFFFF;
  for (let i = 0; i < bytes.length; i += 1) {
    c = CRC32_TABLE[(c ^ bytes[i]) & 0xFF] ^ (c >>> 8);
  }
  return (c ^ 0xFFFFFFFF) >>> 0;
}

function makeDosDateTime(date = new Date()) {
  const year = Math.max(1980, date.getFullYear()) - 1980;
  const month = date.getMonth() + 1;
  const day = date.getDate();
  const hours = date.getHours();
  const minutes = date.getMinutes();
  const seconds = Math.floor(date.getSeconds() / 2);
  const dosDate = (year << 9) | (month << 5) | day;
  const dosTime = (hours << 11) | (minutes << 5) | seconds;
  return { dosDate, dosTime };
}

function writeUint16LE(view, offset, value) {
  view.setUint16(offset, value & 0xFFFF, true);
}

function writeUint32LE(view, offset, value) {
  view.setUint32(offset, value >>> 0, true);
}

function concatChunks(chunks) {
  const total = chunks.reduce((sum, chunk) => sum + chunk.length, 0);
  const out = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.length;
  }
  return out;
}

function createZipBlob(entries) {
  const fileEntries = entries.map((entry) => ({
    name: entry.name.replace(/\\/g, '/'),
    data: toUint8Array(entry.data),
  }));

  const localChunks = [];
  const centralChunks = [];
  const offsets = [];
  let cursor = 0;
  const { dosDate, dosTime } = makeDosDateTime();

  for (const entry of fileEntries) {
    const nameBytes = toUint8Array(entry.name);
    const dataBytes = entry.data;
    const crc = crc32(dataBytes);

    const localHeader = new Uint8Array(30 + nameBytes.length);
    const localView = new DataView(localHeader.buffer);
    writeUint32LE(localView, 0, 0x04034b50);
    writeUint16LE(localView, 4, 20);
    writeUint16LE(localView, 6, 0);
    writeUint16LE(localView, 8, 0);
    writeUint16LE(localView, 10, dosTime);
    writeUint16LE(localView, 12, dosDate);
    writeUint32LE(localView, 14, crc);
    writeUint32LE(localView, 18, dataBytes.length);
    writeUint32LE(localView, 22, dataBytes.length);
    writeUint16LE(localView, 26, nameBytes.length);
    writeUint16LE(localView, 28, 0);
    localHeader.set(nameBytes, 30);

    offsets.push(cursor);
    localChunks.push(localHeader, dataBytes);
    cursor += localHeader.length + dataBytes.length;
  }

  let centralSize = 0;
  for (let i = 0; i < fileEntries.length; i += 1) {
    const entry = fileEntries[i];
    const nameBytes = toUint8Array(entry.name);
    const dataBytes = entry.data;
    const crc = crc32(dataBytes);
    const localOffset = offsets[i];

    const centralHeader = new Uint8Array(46 + nameBytes.length);
    const centralView = new DataView(centralHeader.buffer);
    writeUint32LE(centralView, 0, 0x02014b50);
    writeUint16LE(centralView, 4, 20);
    writeUint16LE(centralView, 6, 20);
    writeUint16LE(centralView, 8, 0);
    writeUint16LE(centralView, 10, 0);
    writeUint16LE(centralView, 12, dosTime);
    writeUint16LE(centralView, 14, dosDate);
    writeUint32LE(centralView, 16, crc);
    writeUint32LE(centralView, 20, dataBytes.length);
    writeUint32LE(centralView, 24, dataBytes.length);
    writeUint16LE(centralView, 28, nameBytes.length);
    writeUint16LE(centralView, 30, 0);
    writeUint16LE(centralView, 32, 0);
    writeUint16LE(centralView, 34, 0);
    writeUint16LE(centralView, 36, 0);
    writeUint32LE(centralView, 38, 0);
    writeUint32LE(centralView, 42, localOffset);
    centralHeader.set(nameBytes, 46);

    centralChunks.push(centralHeader);
    centralSize += centralHeader.length;
  }

  const localData = concatChunks(localChunks);
  const centralData = concatChunks(centralChunks);
  const endRecord = new Uint8Array(22);
  const endView = new DataView(endRecord.buffer);
  writeUint32LE(endView, 0, 0x06054b50);
  writeUint16LE(endView, 4, 0);
  writeUint16LE(endView, 6, 0);
  writeUint16LE(endView, 8, fileEntries.length);
  writeUint16LE(endView, 10, fileEntries.length);
  writeUint32LE(endView, 12, centralData.length);
  writeUint32LE(endView, 16, localData.length);
  writeUint16LE(endView, 20, 0);

  return new Blob([localData, centralData, endRecord], { type: 'application/zip' });
}

async function fetchText(path) {
  const response = await fetch(path, { cache: 'no-store' });
  if (!response.ok) throw new Error(`Failed to fetch ${path}`);
  return await response.text();
}

async function fetchBinary(path) {
  const response = await fetch(path, { cache: 'no-store' });
  if (!response.ok) throw new Error(`Failed to fetch ${path}`);
  return await response.arrayBuffer();
}

async function collectShellFiles() {
  const files = [];
  const textPaths = ['index.html', 'app.js', 'styles.css', 'manifest.webmanifest', 'sw.js', 'README.md'];
  for (const path of textPaths) {
    try {
      files.push({ name: `workspace/${path}`, data: await fetchText(`./${path}`) });
    } catch (error) {
      console.warn(error);
    }
  }

  const binaryPaths = ['assets/icon-192.png', 'assets/icon-512.png'];
  for (const path of binaryPaths) {
    try {
      files.push({ name: `workspace/${path}`, data: await fetchBinary(`./${path}`) });
    } catch (error) {
      console.warn(error);
    }
  }

  return files;
}

async function buildZip() {
  try {
    const projectFiles = state.files.map((file) => ({ name: `project/${file.path}`, data: file.content }));
    const reportFiles = makeProjectReports().map((file) => ({ name: `reports/${file.path.replace(/^reports\//, '')}`, data: file.content }));
    const shellFiles = await collectShellFiles();
    const bundle = {
      generatedAt: new Date().toISOString(),
      project: projectSnapshot(),
    };

    const zip = buildZipFromEntries([
      ...shellFiles,
      ...projectFiles,
      ...reportFiles,
      { name: 'bundle.json', data: JSON.stringify(bundle, null, 2) },
    ]);

    const filename = `${slugify(state.projectName)}-bundle.zip`;
    downloadBlob(zip, filename);
    state.bundleName = filename;
    state.exportCount += 1;
    state.savedAt = new Date().toISOString();
    log(`Exported bundle: ${filename}`);
  } catch (error) {
    state.commandOutput = `Export failed: ${error.message}`;
    log(`Export failed: ${error.message}`);
  }
}

function buildZipFromEntries(entries) {
  return createZipBlob(entries);
}

function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

